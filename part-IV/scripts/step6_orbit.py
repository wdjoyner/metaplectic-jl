"""Verify: Lambda = {h : N(h)=20} is a single free orbit of the twisted Heis action, and
   sum_{h in Lambda} zeta^{h(v)} = 27 (v=0), 9 zeta^{-e(v)} (v good), 0 otherwise.
   Independent recomputation of e_* from scratch (no reuse of step4 internals)."""
import sys; sys.path.insert(0, '.')
import pickle, itertools, cmath
import numpy as np
from collections import Counter

G3 = pickle.load(open('./G3.pkl', 'rb'))['G3']
acts = pickle.load(open('./actions.pkl', 'rb'))
Ms = {k: np.array(v) for k, v in acts['Ms'].items()}
D8 = [np.array(g) for g in acts['D8']]
def apply(M, v): return tuple(int(t) for t in (M @ np.array(v)) % 3)
def neg(v): return tuple((-c) % 3 for c in v)
def hv(h, v): return sum(x*y for x, y in zip(h, v)) % 3
H = list(itertools.product(range(3), repeat=5))
Gset = set(G3)

# rank of span of G3
def rank3(vs):
    M = np.array(vs) % 3; M = M.copy(); r = 0; rows, cols = M.shape
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if M[i, c] % 3: piv = i; break
        if piv is None: continue
        M[[r, piv]] = M[[piv, r]]; M[r] = (M[r]*(1 if M[r, c] == 1 else 2)) % 3
        for i in range(rows):
            if i != r and M[i, c]: M[i] = (M[i] - M[i, c]*M[r]) % 3
        r += 1
    return r
print("rank of span of G3 in V:", rank3(G3))

# --- independent recomputation of admissible e: brute force over ALL D8-invariant odd e ---
# D8-orbits on G3
def orbits(group, pts):
    pts = set(pts); orbs = []
    while pts:
        p = pts.pop(); orb = {p}; fr = [p]
        while fr:
            q = fr.pop()
            for g in group:
                r = apply(g, q)
                if r not in orb: orb.add(r); fr.append(r)
        pts -= orb; orbs.append(sorted(orb))
    return orbs
orbs = orbits(D8, G3)
orb_of = {v: k for k, o in enumerate(orbs) for v in o}
admissible = []
for vals in itertools.product(range(3), repeat=len(orbs)):
    e = {v: vals[orb_of[v]] for v in G3}
    if any(e[neg(v)] != (-e[v]) % 3 for v in G3): continue
    Ns = [sum(1 for v in G3 if hv(h, v) == (-e[v]) % 3)//2 for h in H]
    if set(Ns) <= {11, 20}:
        admissible.append((vals, e, Ns))
print("number of admissible D8-invariant odd e (full search over 3^%d):" % len(orbs), len(admissible))

for vals, e, Ns in admissible:
    Lam = [h for h, n in zip(H, Ns) if n == 20]
    print("\n== e with orbit values", vals, " |Lambda| =", len(Lam))
    # beta_s from e for the two Heis generators
    def beta_of(M):
        for b in H:
            if all(hv(b, v) == (e[apply(M, v)] - e[v]) % 3 for v in G3): return b
        return None
    gensH = {'Ad(1+j)': Ms['Ad(1+j)'], 'Ad(1+ij)': Ms['Ad(1+ij)']}
    betas = {k: beta_of(M) for k, M in gensH.items()}
    print("beta:", betas)
    # twisted action on characters: s.h = (h - beta_s) o s^{-1}
    def inv3(M):
        # inverse mod 3 by power (order 3)
        return (M @ M) % 3
    def act_char(name, h):
        M = gensH[name]; b = betas[name]; Minv = inv3(M)
        hb = tuple((x - y) % 3 for x, y in zip(h, b))
        # (hb o M^{-1})(v) = hb . (M^{-1} v) = (M^{-T} hb) . v
        return tuple(int(t) for t in (Minv.T @ np.array(hb)) % 3)
    # generate group of affine maps on characters
    start = Lam[0]
    orb = {start}; fr = [start]
    while fr:
        h = fr.pop()
        for name in gensH:
            h2 = act_char(name, h)
            if h2 not in orb: orb.add(h2); fr.append(h2)
    print("orbit of one element of Lambda has size", len(orb), "; equals Lambda:", set(orb) == set(Lam))
    # freeness: group generated has order 27?
    # enumerate words up to length and collect distinct affine maps (as permutations of H)
    def as_perm(name): return tuple(act_char(name, h) for h in H)
    gensP = [as_perm(n) for n in gensH]
    idmap = tuple(H); grp = {idmap}; fr = [idmap]
    Hidx = {h: i for i, h in enumerate(H)}
    while fr:
        p = fr.pop()
        for g in gensP:
            q = tuple(g[Hidx[x]] for x in p)
            if q not in grp: grp.add(q); fr.append(q)
    print("order of the group generated by the twisted action:", len(grp))
    stab = sum(1 for p in grp if p[Hidx[start]] == start)
    print("stabilizer order of lambda:", stab)
    # Fourier check
    z = cmath.exp(2j*cmath.pi/3)
    ok = True
    for v in H:
        S = sum(z**hv(h, v) for h in Lam)
        if v == (0,0,0,0,0): target = 27
        elif v in Gset: target = 9*z**((-e[v]) % 3)
        else: target = 0
        if abs(S - target) > 1e-8: ok = False
    print("Fourier identities (27 / 9 zeta^{-e(v)} / 0):", ok)
    # the 20/11 structure per line relative to Lambda
    cnt = Counter()
    for v in G3:
        vals3 = Counter(hv(h, v) for h in Lam)
        cnt[tuple(sorted(vals3.values()))] += 1
    print("distribution of h(v) over Lambda for good v:", dict(cnt))
    pickle.dump({'vals': vals, 'e': e, 'Lambda': Lam, 'betas': betas}, open('./design_%s.pkl' % ''.join(map(str, vals)), 'wb'))
